// One-off: turns Natural Earth land polygons (public domain, naturalearthdata.com) into compact SVG
// paths in the site's Equal Earth projection, written to src/assets/map/land.ts.
//
//   node scripts/make_world_map.mjs <ne_110m_land.geojson> <ne_50m_land.geojson>
//
// Download the two files from github.com/nvkelso/natural-earth-vector (geojson/). Re-run only if
// the projection in src/lib/places.ts changes.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { LAT_BOTTOM, project } from '../src/lib/places.ts';

const [low, high] = process.argv.slice(2);
if (!low || !high) {
  console.error('usage: node scripts/make_world_map.mjs <ne_110m_land.geojson> <ne_50m_land.geojson>');
  process.exit(1);
}

// Where the /travel map zooms in (around the pins): fine detail there, coarse elsewhere.
// [west, south, east, north] in degrees.
const DETAIL = [
  [-15, 33, 32, 62], // Europe
  [95, 3, 140, 45], // China, Philippines
  [-128, 18, -62, 52], // mainland USA
  [-162, 17, -153, 24], // Hawaii
];
const inDetail = (ring) => {
  const lngs = ring.map(([lng]) => lng), lats = ring.map(([, lat]) => lat);
  const [w, s, e, n] = [Math.min(...lngs), Math.min(...lats), Math.max(...lngs), Math.max(...lats)];
  return DETAIL.some(([W, S, E, N]) => w <= E && e >= W && s <= N && n >= S);
};

/**
 * Path for all land rings, dropping points closer than `tol` map units (or `tolDetail` inside
 * the DETAIL boxes) and islands smaller than `minExtent`.
 */
function toPath(file, tol, minExtent, decimals, tolDetail = tol) {
  const geo = JSON.parse(readFileSync(file, 'utf8'));
  const f = 10 ** decimals;
  const r = (n) => Math.round(n * f) / f;
  const parts = [];
  for (const feature of geo.features) {
    const g = feature.geometry;
    const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
    for (const poly of polys) {
      const ring = poly[0]; // outer ring only: lakes aren't needed at this scale
      if (Math.max(...ring.map(([, lat]) => lat)) < LAT_BOTTOM) continue; // Antarctica
      const detailed = inDetail(ring);
      const t = detailed ? tolDetail : tol;
      const pts = ring.map(([lng, lat]) => project(Math.max(lat, LAT_BOTTOM), lng));
      const xs = pts.map((p) => p.x), ys = pts.map((p) => p.y);
      const min = detailed ? minExtent / 3 : minExtent;
      if (Math.max(...xs) - Math.min(...xs) < min && Math.max(...ys) - Math.min(...ys) < min) continue;
      const kept = [pts[0]];
      for (const p of pts.slice(1)) {
        const last = kept[kept.length - 1];
        if (Math.hypot(p.x - last.x, p.y - last.y) >= t) kept.push(p);
      }
      if (kept.length < 3) continue;
      let d = `M${r(kept[0].x)} ${r(kept[0].y)}`;
      let [px, py] = [r(kept[0].x), r(kept[0].y)];
      for (const p of kept.slice(1)) {
        const [x, y] = [r(p.x), r(p.y)];
        const dx = r(x - px), dy = r(y - py);
        if (dx === 0 && dy === 0) continue;
        d += `l${dx}${dy < 0 ? '' : ' '}${dy}`;
        [px, py] = [x, y];
      }
      parts.push(d + 'z');
    }
  }
  return parts.join('');
}

const LOW = toPath(low, 1.2, 1.5, 1); // home page: whole world, small
const HIGH = toPath(high, 1.2, 1.5, 1, 0.3); // /travel: fine where it zooms (Europe, US, East Asia)

mkdirSync('src/assets/map', { recursive: true });
writeFileSync(
  'src/assets/map/land.ts',
  `// Generated by scripts/make_world_map.mjs from Natural Earth (public domain). Do not edit.\n` +
    `export const LAND_LOW = ${JSON.stringify(LOW)};\nexport const LAND_HIGH = ${JSON.stringify(HIGH)};\n`,
);
console.log(`land.ts written: low ${(LOW.length / 1024).toFixed(0)} KB, high ${(HIGH.length / 1024).toFixed(0)} KB`);
